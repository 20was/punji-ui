// Writes site/dist/_headers (read by Cloudflare static assets): security headers for every page, with a
// Content-Security-Policy whose script-src allows this build's inline scripts by hash and nothing else inline,
// and long-lived caching for the hashed files under /assets/. Run last in `site:build`, after the prerender.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../site/dist/', import.meta.url));
const pages = readdirSync(dist, { recursive: true }).filter((f) => String(f).endsWith('.html'));
const hashes = new Set();
for (const file of pages) {
  // Only classic inline scripts run; JSON-LD (`type="application/ld+json"`) is data and needs no hash.
  for (const [, body] of readFileSync(join(dist, String(file)), 'utf8').matchAll(/<script>([\s\S]*?)<\/script>/g)) {
    hashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`);
  }
}
const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].sort().join(' ')}`.trim(),
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  // The phone-width preview is this site's own page in an iframe.
  "frame-src 'self'",
  "frame-ancestors 'self'",
  "worker-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  'upgrade-insecure-requests',
].join('; ');
const lines = [
  '# Generated by scripts/site-headers.mjs. Do not edit.',
  '/*',
  `  Content-Security-Policy: ${csp}`,
  '  Strict-Transport-Security: max-age=31536000; includeSubDomains',
  '  X-Content-Type-Options: nosniff',
  '  Referrer-Policy: strict-origin-when-cross-origin',
  '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()',
  '  Cross-Origin-Opener-Policy: same-origin',
  '  X-Frame-Options: SAMEORIGIN',
  '/assets/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
];
writeFileSync(join(dist, '_headers'), lines.join('\n'));
console.log(`headers: CSP with ${hashes.size} inline script hash(es) for ${pages.length} pages`);

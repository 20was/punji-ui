// Splits the page registry and the generated API data into the small files the browser loads, so no page
// downloads every other page's text (see site/README.md, "Loading"):
//   nav.json            groups and one slim entry per page: what the shell (sidebar, router) needs on every page
//   home.json           the few extra fields the overview reads
//   search.json         the search index (loaded when the search opens)
//   pages/<slug>.json   one page's full entry, its API entries, its related-page cards, `usedIn` (the showcase screens
//                       built from the page) and `modified` (the date its sources last changed)
//   dates.json          slug to that date, for the prerender's sitemap and JSON-LD (scripts/site-dates.mjs)
//   routes/<slug>.ts    the page's route module: that data plus its examples and guide files (one chunk per page)
// Run by site-gen after api.json is written (`node scripts/site-pages.mjs`), and by the dev server (site/vite.config.ts)
// through writePageData when a registry file changes.
// Reads site/src/generated/api.json, so site-gen must have run once.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { pageDates } from './site-dates.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const out = resolve(root, 'site/src/generated');

// Only rewrite what changed, so the dev server reloads what an edit touched and nothing else.
const writeText = (file, text) => {
  let current;
  try { current = readFileSync(file, 'utf8'); } catch { current = undefined; }
  if (current !== text) writeFileSync(file, text);
};
const write = (file, data) => writeText(file, `${JSON.stringify(data)}\n`);

/** Write the split files from the registry module (site/src/registry.ts) and generated/api.json. */
export function writePageData({ PAGES, GROUPS, leadOf, navTitleOf }) {
  const api = JSON.parse(readFileSync(resolve(out, 'api.json'), 'utf8'));
  const nav = (p) => ({ slug: p.slug, title: p.title, ...(navTitleOf(p) !== p.title ? { navTitle: navTitleOf(p) } : {}), group: p.group, kind: p.kind });
  const card = (p) => ({ ...nav(p), lead: leadOf(p) });

  mkdirSync(resolve(out, 'pages'), { recursive: true });
  mkdirSync(resolve(out, 'routes'), { recursive: true });
  write(resolve(out, 'nav.json'), { groups: GROUPS.map(({ id, title }) => ({ id, title })), pages: PAGES.map(nav) });
  write(resolve(out, 'home.json'), { showcase: PAGES.filter((p) => p.kind === 'showcase').map(card) });
  write(resolve(out, 'search.json'), PAGES.map((p) => ({ ...card(p), description: p.description, api: [...new Set(p.api.map((a) => a.name))] })));
  const dates = pageDates(PAGES, root);
  write(resolve(out, 'dates.json'), dates);
  for (const p of PAGES) {
    const entries = Object.fromEntries([...new Set(p.api.map((a) => a.name))].filter((name) => api[name]).map((name) => [name, api[name]]));
    const related = p.related.map((slug) => PAGES.find((o) => o.slug === slug)).filter(Boolean).map(card);
    // The reverse of a showcase's "Built from": every pattern that uses this page, so components link to real screens.
    const usedIn = p.kind === 'showcase' ? [] : PAGES.filter((o) => o.kind === 'showcase' && o.related.includes(p.slug)).map(card);
    write(resolve(out, 'pages', `${p.slug}.json`), { page: { ...p, lead: leadOf(p) }, api: entries, related, usedIn, modified: dates[p.slug] });
    writeText(resolve(out, 'routes', `${p.slug}.ts`), routeModule(p));
  }
  // A page that was removed or renamed must not leave its old files behind (the client would still bundle them).
  for (const [dir, ext] of [['pages', 'json'], ['routes', 'ts']]) {
    const keep = new Set(PAGES.map((p) => `${p.slug}.${ext}`));
    for (const file of readdirSync(resolve(out, dir))) if (!keep.has(file)) rmSync(resolve(out, dir, file));
  }
}

/**
 * One page's route module (generated/routes/<slug>.ts): its data, every example's component, source text and layout
 * CSS, and its guide files' text, as static imports. The browser loads it as one chunk (plus the package code it
 * shares with other pages), so a page arrives in one step and no page pays for a list of every other page's files.
 */
function routeModule(p) {
  const lines = ['// Generated by scripts/site-pages.mjs from site/src/registry.ts. Do not edit.', "import type { RouteModule } from '../../app/load.ts';", `import data from '../pages/${p.slug}.json';`];
  const examples = [];
  p.examples.forEach((ex, i) => {
    const file = `../../examples/${p.slug}/${ex.id}`;
    lines.push(`import * as e${i} from '${file}.tsx';`, `import s${i} from '${file}.tsx?raw';`);
    const css = existsSync(resolve(root, 'site/src/examples', p.slug, `${ex.id}.css`));
    if (css) lines.push(`import c${i} from '${file}.css?raw';`);
    examples.push(`${JSON.stringify(ex.id)}: { Component: e${i}.default, source: s${i}${css ? `, css: c${i}` : ''} }`);
  });
  const guides = [];
  const files = [...new Set((p.guide ?? []).flatMap((section) => (section.code ?? []).map((c) => c.file).filter(Boolean)))];
  files.forEach((file, i) => {
    lines.push(`import g${i} from '../../guides/${p.slug}/${file}.tsx?raw';`);
    guides.push(`${JSON.stringify(file)}: g${i}`);
  });
  lines.push(
    '',
    'const route: RouteModule = {',
    "  data: data as unknown as RouteModule['data'],",
    `  examples: {${examples.length ? `\n    ${examples.join(',\n    ')},\n  ` : ''}},`,
    `  guides: {${guides.length ? `\n    ${guides.join(',\n    ')},\n  ` : ''}},`,
    '};',
    'export default route;',
    '',
  );
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) writePageData(await import(/* @vite-ignore */ resolve(root, 'site/src/registry.ts')));

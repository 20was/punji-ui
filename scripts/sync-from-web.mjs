#!/usr/bin/env node
// Mirrors Punji's web kit into this package. Punji's web app is the source of
// truth; this script copies the modules the manifest marks ship or adapt,
// applies the documented adapters, splits the kit's stylesheet into one file
// per module, maps the design tokens to --pu-* variables (light and dark),
// and regenerates the barrel, the package exports, the size budgets and the
// README's component table. It fails loudly on anything it cannot classify.
//
//   PUNJI_WEB_DIR=/path/to/punji-web npm run sync
//   node scripts/sync-from-web.mjs --from /path/to/punji-web
//
// Re-runnable and idempotent: the same source gives the same files. Generated
// files carry a header; files the script generated before and no longer
// produces are removed. See CONTRIBUTING.md, "How the kit is kept in sync".
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BARREL_EXTRA, CSS_BUDGET, CSS_OWNERS, CSS_SOURCES, DENYLIST, EXTERNAL, KEYFRAME_OWNERS, MODULES, SHARED_SELECTORS, TOKEN_SOURCES, TOTAL_BUDGET } from './sync/manifest.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const MARK = 'Generated by scripts/sync-from-web.mjs';
const KIT = 'src/components/kit';
const problems = [];
const fail = (msg) => problems.push(msg);

function sourceDir() {
  const i = process.argv.indexOf('--from');
  const dir = i > 0 ? process.argv[i + 1] : process.env.PUNJI_WEB_DIR;
  if (!dir) {
    console.error('sync: give the Punji web checkout with --from <dir> or PUNJI_WEB_DIR=<dir>');
    process.exit(2);
  }
  if (!existsSync(join(dir, KIT, 'index.ts'))) {
    console.error(`sync: ${dir} does not look like the Punji web repository (no kit barrel)`);
    process.exit(2);
  }
  return dir;
}

const WEB = sourceDir();
const read = (p) => readFileSync(join(WEB, p), 'utf8');
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase();
const moduleOf = (file) => file.replace(/\.tsx?$/, '');
const sha = (s) => createHash('sha256').update(s).digest('hex');

/* ------------------------------------------------------------ classify -- */

const kitFiles = readdirSync(join(WEB, KIT)).filter((f) => /\.tsx?$/.test(f) && f !== 'index.ts');
for (const f of kitFiles) if (!MODULES[f]) fail(`new kit module ${f}: classify it in scripts/sync/manifest.mjs (ship, adapt, pending or web-only)`);
for (const f of Object.keys(MODULES)) if (!kitFiles.includes(f)) fail(`${f} is in the manifest but no longer in the kit: remove it from the manifest`);
for (const [f, m] of Object.entries(MODULES)) if (m.status !== 'ship' && !m.reason) fail(`${f}: status ${m.status} needs a reason`);

const shipped = kitFiles.filter((f) => MODULES[f] && (MODULES[f].status === 'ship' || MODULES[f].status === 'adapt')).toSorted();
const shippedNames = new Set(shipped.map(moduleOf));
const dirOf = (file) => kebab(moduleOf(file));

/* --------------------------------------------------------- TypeScript -- */

function applyEdits(file, text) {
  for (const e of MODULES[file].edits ?? []) {
    const n = text.split(e.find).length - 1;
    const want = e.count ?? 1;
    if (n !== want) {
      fail(`${file}: adapter edit expected ${want} match(es), found ${n}:\n    ${JSON.stringify(e.find.slice(0, 120))}`);
      continue;
    }
    text = text.split(e.find).join(e.replace);
  }
  return text;
}

function extractHelper(src, name) {
  const fn = new RegExp(`^export function ${name}\\b[\\s\\S]*?^}\\n`, 'm').exec(src);
  if (fn) return fn[0];
  const c = new RegExp(`^export const ${name}\\b[^\\n]*;\\n`, 'm').exec(src);
  return c ? c[0] : null;
}

const externalChecked = new Set();
function checkExternal(spec, names, file) {
  const ext = EXTERNAL[spec];
  if (!ext) return fail(`${file}: imports ${spec}, which the package cannot provide (add an adapter or an EXTERNAL entry)`);
  for (const n of names) {
    if (!ext.names[n]) {
      fail(`${file}: imports ${n} from ${spec}; src/internal does not provide it (port it, then add its hash to EXTERNAL)`);
      continue;
    }
    const key = `${spec}#${n}`;
    if (externalChecked.has(key)) continue;
    externalChecked.add(key);
    const body = extractHelper(read(`src/${spec.replace(/^\.\.\/\.\.\//, '')}.ts`), n);
    if (!body) fail(`${spec}: helper ${n} not found`);
    else if (sha(body) !== ext.names[n]) fail(`${spec}: helper ${n} changed upstream (sha256 ${sha(body)}): review ${ext.to} and update the hash in EXTERNAL`);
  }
  return ext.to;
}

const NEEDS_CLIENT = [/\buse[A-Z]\w*\(/, /\bcreatePortal\b/, /\bon[A-Z]\w*=\{\s*\(/, /\bon[A-Z]\w*=\{\s*\w+\s*=>/, /\brequestAnimationFrame\b/];

function transformTs(file) {
  let text = applyEdits(file, read(`${KIT}/${file}`));
  for (const line of text.split('\n')) if (!/^import\b/.test(line)) for (const r of DENYLIST) if (r.test(line)) fail(`${file}: "${line.trim()}" matches the public-repo denylist ${r} (add an adapter edit)`);
  text = text.replace(/^import '[^']+\.css';\n/gm, '');
  text = text.replace(/^\s*\/\/ eslint-disable-next-line react-refresh\/only-export-components\n/gm, '');
  text = text.replace(/\/\/ eslint-disable-next-line react-hooks\/exhaustive-deps/g, '// oxlint-disable-next-line react/exhaustive-deps');
  text = text.replace(/^(import\s+(type\s+)?)([\s\S]*?)\s+from\s+'([^']+)';$/gm, (line, head, _t, what, spec) => {
    if (spec === 'react' || spec === 'react-dom' || spec === 'react-dom/client') return line;
    if (spec.startsWith('../internal/') && /^[\w-]+\.tsx?$/.test(spec.slice(12))) return line;
    if (spec.startsWith('./')) {
      const target = spec.slice(2);
      const f = kitFiles.find((k) => moduleOf(k) === target);
      if (!f) return fail(`${file}: imports ${spec}, not a kit module`), line;
      if (!shippedNames.has(target)) return fail(`${file}: imports ${target}, which is ${MODULES[f].status} (ship it too, or adapt the import away)`), line;
      return `${head}${what} from '../${dirOf(f)}/${f}';`;
    }
    if (spec.startsWith('../../')) {
      const names = [...what.replace(/[{}]/g, '').matchAll(/(?:type\s+)?(\w+)(?:\s+as\s+\w+)?/g)].map((m) => m[1]);
      const to = checkExternal(spec, names, file);
      return `${head}${what} from '${to}';`;
    }
    fail(`${file}: imports ${spec}; the package depends on React only (adapt this import away)`);
    return line;
  });
  if (/from 'react-router/.test(text)) fail(`${file}: still imports a router`);
  const client = NEEDS_CLIENT.some((r) => r.test(text));
  if (client && !text.startsWith("'use client'")) text = `'use client';\n\n${text}`;
  const header = `// ${MARK} from Punji's web kit. Do not edit here:\n// change it in Punji, then sync (CONTRIBUTING.md, "How the kit is kept in sync").\n`;
  return client ? text.replace("'use client';\n\n", `'use client';\n\n${header}`) : `${header}${text}`;
}

/* ---------------------------------------------------------------- CSS -- */

/** Splits CSS into top-level nodes: { kind: 'rule' | 'at', prelude, body } (comments dropped). */
function parseCss(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const nodes = [];
  let i = 0;
  while (i < css.length) {
    while (i < css.length && /\s/.test(css[i])) i++;
    if (i >= css.length) break;
    const open = css.indexOf('{', i);
    const semi = css.indexOf(';', i);
    if (semi !== -1 && (open === -1 || semi < open)) {
      nodes.push({ kind: 'stmt', prelude: css.slice(i, semi).trim(), body: null });
      i = semi + 1;
      continue;
    }
    if (open === -1) throw new Error(`css: unexpected trailing text: ${css.slice(i, i + 60)}`);
    let depth = 0;
    let j = open;
    let quote = null;
    for (; j < css.length; j++) {
      const c = css[j];
      if (quote) {
        if (c === quote && css[j - 1] !== '\\') quote = null;
      } else if (c === '"' || c === "'") quote = c;
      else if (c === '{') depth++;
      else if (c === '}' && --depth === 0) break;
    }
    const prelude = css.slice(i, open).trim().replace(/\s+/g, ' ');
    const body = css.slice(open + 1, j);
    nodes.push({ kind: prelude.startsWith('@') ? 'at' : 'rule', prelude, body });
    i = j + 1;
  }
  return nodes;
}

function splitTop(s, sep) {
  const out = [];
  let depth = 0;
  let cur = '';
  for (const c of s) {
    if (c === '(') depth++;
    if (c === ')') depth--;
    if (c === sep && depth === 0) {
      out.push(cur);
      cur = '';
    } else cur += c;
  }
  if (cur.trim()) out.push(cur);
  return out.map((x) => x.trim()).filter(Boolean);
}

function ownerOfClass(cls) {
  const hits = Object.entries(CSS_OWNERS).filter(([, rs]) => rs.some((r) => r.test(cls)));
  if (hits.length !== 1) {
    fail(hits.length ? `css: .${cls} matches ${hits.map((h) => h[0]).join(' and ')} in CSS_OWNERS` : `css: .${cls} belongs to no module: add it to CSS_OWNERS`);
    return null;
  }
  return hits[0][0];
}

function ownersOfSelector(sel) {
  if (SHARED_SELECTORS[sel]) return SHARED_SELECTORS[sel];
  const m = /\.(kit-[\w-]+)/.exec(sel);
  if (!m) {
    fail(`css: selector "${sel}" names no kit class`);
    return [];
  }
  const o = ownerOfClass(m[1]);
  return o ? [o] : [];
}

const normBody = (b) => b.replace(/\s+/g, ' ').replace(/\s*;\s*$/, '').trim();

/** Distributes nodes to owners: Map owner -> array of CSS text, in source order. */
function distribute(nodes, out, wrap = (t) => t) {
  for (const n of nodes) {
    if (n.kind === 'stmt') {
      fail(`css: top-level statement "${n.prelude}" is not handled`);
      continue;
    }
    if (n.kind === 'at') {
      if (n.prelude.startsWith('@keyframes')) {
        const name = n.prelude.split(/\s+/)[1];
        const o = KEYFRAME_OWNERS[name];
        if (!o) fail(`css: @keyframes ${name} has no owner in KEYFRAME_OWNERS`);
        else push(out, o, wrap(`@keyframes ${name} { ${normBody(n.body)} }`));
      } else if (n.prelude.startsWith('@media') || n.prelude.startsWith('@supports')) {
        distribute(parseCss(n.body), out, (t) => wrap(`${n.prelude} { ${t} }`));
      } else fail(`css: at-rule ${n.prelude} is not handled`);
      continue;
    }
    const groups = new Map();
    for (const sel of splitTop(n.prelude, ',')) for (const o of ownersOfSelector(sel)) groups.set(o, [...(groups.get(o) ?? []), sel]);
    for (const [o, sels] of groups) push(out, o, wrap(`${sels.join(', ')} { ${normBody(n.body)} }`));
  }
}

function push(map, owner, text) {
  if (!map.has(owner)) map.set(owner, []);
  map.get(owner).push(text);
}

/* ------------------------------------------------------------- tokens -- */

function declarations(body) {
  const map = new Map();
  for (const d of splitTop(body.replace(/\/\*[\s\S]*?\*\//g, ''), ';')) {
    const k = d.indexOf(':');
    if (k < 0) continue;
    const name = d.slice(0, k).trim();
    if (name.startsWith('--')) map.set(name.slice(2), d.slice(k + 1).trim().replace(/\s+/g, ' '));
  }
  return map;
}

function block(nodes, prelude) {
  const n = nodes.find((x) => x.prelude === prelude);
  if (!n) fail(`tokens: no "${prelude}" block`);
  return n ? declarations(n.body) : new Map();
}

function resolveV2(v, v2, depth = 0) {
  return v.replace(/var\(--(v2-[\w-]+)\)/g, (_, name) => {
    if (depth > 8 || !v2.has(name)) return fail(`tokens: --${name} cannot be resolved`), 'initial';
    return resolveV2(v2.get(name), v2, depth + 1);
  });
}

function buildTokens(usedNames) {
  const base = parseCss(read(TOKEN_SOURCES.base));
  const v2Light = block(base, ":root, [data-theme='light']");
  const v2Dark = new Map([...v2Light, ...block(base, "[data-theme='dark']")]);
  const sem = parseCss(read(TOKEN_SOURCES.semantic));
  const semLight = block(sem, ':root');
  const semDark = new Map([...semLight, ...block(sem, "[data-theme='dark']")]);
  const theme = parseCss(read(TOKEN_SOURCES.theme));
  const all = block(theme, 'html[data-theme]');
  const light = new Map([...semLight, ...all, ...block(theme, "html[data-theme='light']")]);
  const dark = new Map([...semDark, ...all, ...block(theme, "html[data-theme='dark']")]);

  const keep = new Set();
  const queue = [...usedNames];
  while (queue.length) {
    const name = queue.pop();
    if (keep.has(name)) continue;
    if (!light.has(name) && !dark.has(name)) {
      fail(`tokens: the kit reads --${name}, which no token file defines`);
      continue;
    }
    keep.add(name);
    for (const v of [light.get(name), dark.get(name)]) for (const m of (v ?? '').matchAll(/var\(--([\w-]+)/g)) if (!m[1].startsWith('v2-')) queue.push(m[1]);
  }
  const out = (map, v2) => {
    const res = new Map();
    for (const name of [...keep].toSorted()) {
      const v = map.get(name) ?? light.get(name);
      res.set(name, resolveV2(v, v2).replace(/var\(--([\w-]+)/g, (_, n) => `var(--pu-${n}`));
    }
    return res;
  };
  return { light: out(light, v2Light), dark: out(dark, v2Dark) };
}

/* ------------------------------------------------------------ registry -- */

function docsPages() {
  const src = read('src/design/registry.ts');
  const pages = [];
  for (const m of src.matchAll(/\{ path: '([^']+)', title: '([^']+)', group: '([^']+)'[^\n]*?component: \{ exports: \[([^\]]*)\](?:, module: (null|'[^']+'))?/g)) {
    pages.push({ path: m[1], title: m[2], group: m[3], exports: [...m[4].matchAll(/'(\w+)'/g)].map((x) => x[1]) });
  }
  if (pages.length < 10) fail('registry: could not read the docs pages (did the registry format change?)');
  return pages;
}

/* --------------------------------------------------------------- write -- */

const decl = (map, names) => names.map((n) => `    --pu-${n}: ${map.get(n)};`).join('\n');
const cell = (v) => `\`${v.replace(/\|/g, '\\|')}\``;
const walk = (d) => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]));

const written = new Set();
function write(rel, text) {
  written.add(rel);
  const p = join(ROOT, rel);
  mkdirSync(dirname(p), { recursive: true });
  if (existsSync(p) && readFileSync(p, 'utf8') === text) return;
  writeFileSync(p, text);
}

function main() {
  // TypeScript modules.
  const ts = new Map();
  for (const f of shipped) ts.set(f, transformTs(f));

  // CSS.
  const owned = new Map();
  for (const s of CSS_SOURCES) {
    let css = read(s.file);
    if (s.from) {
      const at = css.indexOf(s.from);
      if (at < 0) fail(`css: marker "${s.from}" not found in ${s.file}`);
      css = css.slice(css.lastIndexOf('/*', at));
    }
    distribute(parseCss(css), owned);
  }
  const used = new Set();
  const locals = new Set();
  for (const texts of owned.values())
    for (const t of texts) {
      for (const m of t.matchAll(/(?:^|[{;\s])--([\w-]+)\s*:/g)) locals.add(m[1]);
      for (const m of t.matchAll(/var\(--([\w-]+)/g)) used.add(m[1]);
    }
  for (const l of locals) used.delete(l);
  // --kit-* properties are a component's own inputs (set inline by its React code), never tokens.
  for (const u of used) if (u.startsWith('kit-')) used.delete(u);
  const tokens = buildTokens(used);
  const rename = (t) => t.replace(/var\(--([\w-]+)/g, (all, n) => (tokens.light.has(n) ? `var(--pu-${n}` : all));


  for (const f of shipped) if (!MODULES[f].budget) fail(`${f}: no size budget in the manifest`);
  const readmeText = readFileSync(join(ROOT, 'README.md'), 'utf8');
  if (!readmeText.includes('<!-- components:start -->') || !readmeText.includes('<!-- components:end -->')) fail('README.md: the components markers are missing');
  if (problems.length) return;

  const cssOwners = ['base', ...shipped.map(dirOf).filter((d) => owned.has(d))];
  for (const d of shipped.map(dirOf)) if (!owned.has(d) && d !== 'format') console.log(`  note: ${d} has no styles of its own`);

  for (const f of shipped) write(`src/${dirOf(f)}/${f}`, ts.get(f));

  const cssHeader = (what) => `/* ${MARK} from Punji's web kit. Do not edit here.\n   ${what} */\n`;
  for (const o of cssOwners) {
    const rules = (owned.get(o) ?? []).map((t) => `  ${rename(t)}`).join('\n');
    write(`src/styles/${o}.css`, `${cssHeader(o === 'base' ? 'Shared by every component: the visually hidden text and the spinner.' : `Styles for ${o}. Needs tokens.css and base.css (styles.css has everything).`)}@layer punji.components {\n${rules}\n}\n`);
  }
  const all = [...tokens.light.keys()];
  const darkNames = all.filter((n) => tokens.dark.get(n) !== tokens.light.get(n) || tokens.light.get(n).includes('var('));
  write(
    'src/styles/tokens.css',
    `${cssHeader("Design tokens, mapped from Punji's theme to --pu-* (docs/tokens.md).\n   Light and dark follow the system; force one with data-theme=\"light\" | \"dark\"\n   on any element. Override any token on :root or a subtree; everything is in\n   cascade layers, so your own unlayered CSS wins without !important.")}@layer punji.tokens {\n  :root,\n  [data-theme='light'] {\n    color-scheme: light;\n${decl(tokens.light, all)}\n  }\n\n  [data-theme='dark'] {\n    color-scheme: dark;\n${decl(tokens.dark, darkNames)}\n  }\n\n  @media (prefers-color-scheme: dark) {\n    :root:not([data-theme='light']) {\n      color-scheme: dark;\n${decl(tokens.dark, darkNames).replace(/^ {4}/gm, '      ')}\n    }\n  }\n}\n`,
  );
  write(
    'docs/tokens.md',
    `<!-- ${MARK}. Do not edit here. -->\n\n# Design tokens\n\nEvery colour, size, radius, font and duration the components read is a \`--pu-*\`\nCSS variable, defined in \`@punji/ui/tokens.css\` inside the \`punji.tokens\` cascade\nlayer. The values are Punji's own theme (graphite and lime in dark, a sage\nground with off-white cards in light), mapped one to one: Punji's \`--name\`\nis \`--pu-name\` here. A token that refers to another token keeps the\nreference, so overriding \`--pu-color-accent\` also moves what is built on it.\n\nLight and dark follow \`prefers-color-scheme\`; \`data-theme="light"\` or\n\`data-theme="dark"\` on any element forces one for that subtree. A dash in\nthe dark column means the light value applies in both.\n\n| Token | Light | Dark |\n| --- | --- | --- |\n${all.map((n) => `| \`--pu-${n}\` | ${cell(tokens.light.get(n))} | ${darkNames.includes(n) && tokens.dark.get(n) !== tokens.light.get(n) ? cell(tokens.dark.get(n)) : '-'} |`).join('\n')}\n`,
  );
  write('src/styles/styles.css', `${cssHeader("Everything: tokens, then every component. Import once at the app root:\n   import '@punji/ui/styles.css'. For the smallest CSS, import tokens.css,\n   base.css and only the component files you draw (@punji/ui/css/<name>.css).")}@layer punji.tokens, punji.components;\n@import './tokens.css';\n${cssOwners.map((o) => `@import './${o}.css';`).join('\n')}\n`);

  // Barrel: the web barrel's lines for shipped modules, in its order.
  const lines = [];
  for (const m of read(`${KIT}/index.ts`).matchAll(/^export \{([^}]*)\} from '\.\/(\w+)';$/gm)) {
    if (!shippedNames.has(m[2])) continue;
    const f = shipped.find((x) => moduleOf(x) === m[2]);
    lines.push(`export {${m[1]}} from './${dirOf(f)}/${f}';`);
  }
  lines.push(...BARREL_EXTRA);
  write('src/index.ts', `// ${MARK} from Punji's web kit's barrel. Do not edit here.\n// The barrel is side-effect free ("sideEffects" lists CSS only), so bundlers\n// drop what an app does not import. Every module also has its own subpath\n// (@punji/ui/<module>), the same subpaths Punji's own code imports.\n${lines.join('\n')}\n`);

  // package.json exports.
  const pkgPath = join(ROOT, 'package.json');
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  const exp = { '.': { types: './dist/index.d.ts', default: './dist/index.js' } };
  for (const f of shipped) {
    const base = `./dist/${dirOf(f)}/${moduleOf(f)}`;
    exp[`./${dirOf(f)}`] = { types: `${base}.d.ts`, default: `${base}.js` };
  }
  Object.assign(exp, { './styles.css': './dist/styles.css', './tokens.css': './dist/tokens.css', './css/*.css': './dist/css/*.css', './package.json': './package.json' });
  pkg.exports = exp;
  write('package.json', `${JSON.stringify(pkg, null, 2)}\n`);

  // Size budgets: each module alone, everything at once, the CSS.
  const size = shipped.map((f) => ({ name: `${dirOf(f)} (import from '@punji/ui/${dirOf(f)}')`, path: `dist/${dirOf(f)}/${moduleOf(f)}.js`, import: '*', limit: MODULES[f].budget, gzip: true }));
  for (const s of size) if (!s.limit) fail(`${s.path}: no budget in the manifest`);
  size.push({ name: "Everything (import * from '@punji/ui')", path: 'dist/index.js', import: '*', limit: TOTAL_BUDGET, gzip: true });
  size.push({ name: 'styles.css (all tokens and components)', path: 'dist/styles.css', limit: CSS_BUDGET.styles, rolldown: false, gzip: true });
  size.push({ name: 'tokens.css', path: 'dist/tokens.css', limit: CSS_BUDGET.tokens, rolldown: false, gzip: true });
  write('.size-limit.json', `${JSON.stringify(size, null, 2)}\n`);

  // README component table.
  const pages = docsPages();
  const rows = [];
  for (const f of shipped) {
    const names = [...ts.get(f).matchAll(/^export (?:function|const) (\w+)/gm)].map((m) => m[1]);
    const docs = pages.filter((p) => p.exports.some((e) => names.includes(e))).map((p) => `[${p.title}](https://design.punji.app${p.path})`);
    const comps = names.filter((n) => /^[A-Z]/.test(n));
    rows.push(`| ${(comps.length ? comps : names).map((n) => `\`${n}\``).join(', ')} | \`@punji/ui/${dirOf(f)}\` | ${docs.length ? docs.join(' · ') : '-'} |`);
  }
  const readmePath = join(ROOT, 'README.md');
  const readme = readFileSync(readmePath, 'utf8');
  const start = '<!-- components:start -->';
  const end = '<!-- components:end -->';
  if (!readme.includes(start) || !readme.includes(end)) fail('README.md: the components markers are missing');
  else {
    const table = `${start}\n<!-- ${MARK}. -->\n\n| Exports | Subpath | Docs |\n| --- | --- | --- |\n${rows.join('\n')}\n\n${end}`;
    write('README.md', readme.replace(new RegExp(`${start}[\\s\\S]*?${end}`), table));
  }

  // Remove what an earlier run generated and this one did not.
  for (const p of walk(join(ROOT, 'src'))) {
    const rel = p.slice(ROOT.length);
    if (!written.has(rel) && readFileSync(p, 'utf8').includes(MARK)) {
      rmSync(p);
      console.log(`  removed ${rel}`);
    }
  }
  for (const d of readdirSync(join(ROOT, 'src'))) {
    const p = join(ROOT, 'src', d);
    if (statSync(p).isDirectory() && readdirSync(p).length === 0) rmSync(p, { recursive: true });
  }

  // Record the source commit, for the pull request.
  let commit = 'unknown';
  try {
    commit = execFileSync('git', ['-C', WEB, 'rev-parse', '--short=12', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch {
    /* not a git checkout */
  }
  const counts = Object.values(MODULES).reduce((a, m) => ((a[m.status] = (a[m.status] ?? 0) + 1), a), {});
  console.log(`sync: from Punji web ${commit}: ${shipped.length} modules shipped (${counts.ship ?? 0} as is, ${counts.adapt ?? 0} adapted), ${counts.pending ?? 0} pending, ${counts['web-only'] ?? 0} web-only; ${tokens.light.size} tokens; ${cssOwners.length} stylesheets`);
}

main();
if (problems.length) {
  console.error(`sync: ${problems.length} problem(s), nothing written:\n  - ${problems.join('\n  - ')}`);
  process.exit(1);
}
